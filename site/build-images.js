// The site's pictures for browsers and link previews, drawn from the robot on the home page (pages.js
// ROBOT_SVG): the link preview card (og.png, 1200x630: what iMessage, Slack, X, Discord… show for a link
// to timsrobot.com) and the home-screen icon (apple-touch-icon.png, 180x180, on the page's background).
// The tab icon is the robot itself (favicon.svg, from ROBOT_SVG) and the extension's 32 px icon
// (favicon.ico), so they need nothing drawn here.
// Writes site/src/images.js (the PNGs, base64, for the Worker; it can't read files). Rerun after changing
// the robot or the words: node site/build-images.js. Needs a Chrome: the e2e suite's Chrome for Testing
// (tests/e2e/.browsers), or CHROME=<path to a Chrome binary>. It runs headless, muted, in a throwaway
// profile.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { ROBOT_SVG, TOKENS } from './src/pages.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const OUT = path.join(HERE, 'src', 'images.js');

function chrome() {
  if (process.env.CHROME) return process.env.CHROME;
  const root = path.join(HERE, '..', 'tests', 'e2e', '.browsers', 'chrome');
  const found = [];
  const walk = (d, depth) => {
    if (depth > 7 || !fs.existsSync(d)) return;
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name);
      if (e.isFile() && e.name === 'Google Chrome for Testing') found.push(p);
      else if (e.isDirectory()) walk(p, depth + 1);
    }
  };
  walk(root, 0);
  if (!found.length) throw new Error('no Chrome: run the e2e suite once (it downloads one), or set CHROME=…');
  return found.sort().pop();
}

const robot = (size) => ROBOT_SVG.replace(/ class="robot" aria-hidden="true"/, '').replace('width="128" height="128"', `width="${size}" height="${size}"`);
const doc = (w, h, body) => `<!doctype html><html><head><meta charset="utf-8"><style>${TOKENS}
html, body { margin: 0; width: ${w}px; height: ${h}px; overflow: hidden; background: var(--bg); color: var(--fg);
  font-family: -apple-system, system-ui, "Segoe UI", sans-serif; }
</style></head><body>${body}</body></html>`;

const CARDS = {
  'og.png': [1200, 630, doc(1200, 630, `
<div style="height:100%;display:flex;flex-direction:column;align-items:center;justify-content:center;gap:22px;text-align:center">
  ${robot(230)}
  <div style="font-size:70px;font-weight:800;letter-spacing:-1.5px;line-height:1.05">Tim's Robot Internet Fixer</div>
  <div style="font-size:34px;color:var(--muted)">Fix any website with your own coding agent.</div>
</div>`)],
  'apple-touch-icon.png': [180, 180, doc(180, 180, `
<div style="height:100%;display:flex;align-items:center;justify-content:center">${robot(150)}</div>`)],
};

function shoot(bin, w, h, html, out) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'trif-site-img-'));
  try {
    const page = path.join(dir, 'card.html');
    fs.writeFileSync(page, html);
    execFileSync(bin, ['--headless', '--mute-audio', '--disable-gpu', '--hide-scrollbars', '--no-first-run',
      `--user-data-dir=${path.join(dir, 'profile')}`, '--force-device-scale-factor=1', `--window-size=${w},${h}`,
      `--screenshot=${out}`, `file://${page}`], { stdio: 'ignore', timeout: 60000 });
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

const bin = chrome();
const shot = fs.mkdtempSync(path.join(os.tmpdir(), 'trif-site-shots-'));
const images = {};
for (const [name, [w, h, html]] of Object.entries(CARDS)) {
  const file = path.join(shot, name);
  shoot(bin, w, h, html, file);
  const png = fs.readFileSync(file);
  if (png.readUInt32BE(16) !== w || png.readUInt32BE(20) !== h) throw new Error(`${name}: ${png.readUInt32BE(16)}x${png.readUInt32BE(20)}, not ${w}x${h}`);
  images[`/${name}`] = png.toString('base64');
  if (process.argv.includes('--keep')) fs.copyFileSync(file, path.join(process.argv[process.argv.indexOf('--keep') + 1] || '.', name));
}
fs.rmSync(shot, { recursive: true, force: true });
fs.writeFileSync(OUT, `// Generated by site/build-images.js: don't edit. Run node site/build-images.js instead.
// The site's PNGs (path -> base64): the link preview card and the home-screen icon.
export const IMAGES = ${JSON.stringify(images, null, 1)};
`);
console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${Object.keys(images).join(', ')}`);
